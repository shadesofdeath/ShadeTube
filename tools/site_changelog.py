#!/usr/bin/env python3
"""Turns CHANGELOG.md into site/changelog.js, the data behind the website's changelog page.

    python tools/site_changelog.py

The Pages workflow runs it before publishing, so the site always shows the changelog of the commit it was built from.
"""
import html
import io
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def inline(text):
    """The inline Markdown the changelog uses: **bold**, `code`, [text](url). Everything else is escaped."""
    out = html.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", out)
    out = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2" rel="noopener">\1</a>', out)
    return out


def parse(md):
    versions, cur, item = [], None, None

    def flush():
        nonlocal item
        if cur is not None and item:
            text = " ".join(item).strip()
            m = re.match(r"\*\*(.+?)\*\*\s*[:.]?\s*(.*)$", text, re.S)
            if m and m.group(2):
                body = m.group(2)
                cur["items"].append({"t": inline(m.group(1)), "d": inline(body[:1].upper() + body[1:])})
            else:
                cur["items"].append({"t": "", "d": inline(text)})
        item = None

    for line in md.splitlines():
        h = re.match(r"##\s+(\S+)\s*(?:[—–-]\s*(.+))?$", line)
        if h:
            flush()
            cur = {"v": h.group(1), "date": (h.group(2) or "").strip(), "items": []}
            versions.append(cur)
        elif cur is None:
            continue
        elif re.match(r"-\s+", line):
            flush()
            item = [re.sub(r"^-\s+", "", line).strip()]
        elif line.strip() and item is not None:
            item.append(line.strip())
        elif line.strip():
            item = [line.strip()]   # a paragraph outside a list
        else:
            flush()
    flush()
    return versions


def main():
    with io.open(os.path.join(ROOT, "CHANGELOG.md"), encoding="utf-8") as f:
        versions = parse(f.read())
    out = "// Generated by tools/site_changelog.py from CHANGELOG.md. Do not edit.\nwindow.ST_CHANGELOG = " + \
          json.dumps(versions, ensure_ascii=False, separators=(",", ":")) + ";\n"
    with io.open(os.path.join(ROOT, "site", "changelog.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("%d versions, %d entries" % (len(versions), sum(len(v["items"]) for v in versions)))


if __name__ == "__main__":
    main()
